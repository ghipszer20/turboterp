// Lists course ids that program requirements use but that are in neither the Schedule of Classes
// snapshots nor the Academic Catalog cache, grouped by program, with hints (a "Formerly" twin or a
// suffix-stripped base code). Writes docs/project/unknown-courses.md. Does not edit program files.
//
//   node scripts/unknown-courses.ts [cacheDir]
//
// cacheDir defaults to the main checkout's packages/course-data/.cache (soc-*.json, history/soc-*.json
// and catalog-courses.json). Imports @turboterp/programs, so it is not in plan's package.json.

import { execFileSync } from "node:child_process";
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { programCourseIds } from "@turboterp/audit";
import type { Course } from "@turboterp/course-data";
import { PROGRAMS } from "@turboterp/programs";
import { parseTwinLine } from "../src/twins.ts";

const git = (...args: string[]) => execFileSync("git", args, { encoding: "utf8" }).trim();
const root = git("rev-parse", "--show-toplevel");
const mainCheckout = dirname(resolve(git("rev-parse", "--path-format=absolute", "--git-common-dir")));
const cacheDir = process.argv[2] ?? join(mainCheckout, "packages", "course-data", ".cache");

const readCourses = (p: string) => (JSON.parse(readFileSync(p, "utf8")) as { courses: Course[] }).courses;
const socIn = (dir: string) =>
  existsSync(dir) ? readdirSync(dir).filter((f) => /^soc-\d{6}\.json$/.test(f)).map((f) => join(dir, f)) : [];
const snapshot = new Map<string, Course>();
for (const p of [...socIn(cacheDir), ...socIn(join(cacheDir, "history"))]) for (const c of readCourses(p)) snapshot.set(c.id, c);
const catalogPath = join(cacheDir, "catalog-courses.json");
const catalog = new Map<string, Course>();
if (existsSync(catalogPath)) for (const c of readCourses(catalogPath)) catalog.set(c.id, c);

// Which known course lists an unknown id on its Formerly line.
const formerlyOf = new Map<string, string[]>();
for (const c of [...snapshot.values(), ...catalog.values()]) {
  for (const old of parseTwinLine(c.texts.other["Formerly"], c.id).codes) {
    const list = formerlyOf.get(old) ?? [];
    if (!list.includes(c.id)) list.push(c.id);
    formerlyOf.set(old, list);
  }
}
const known = (id: string) => snapshot.has(id) || catalog.has(id);

function hint(id: string): string {
  const parts: string[] = [];
  const renamed = formerlyOf.get(id);
  if (renamed) parts.push(`formerly of ${renamed.join(", ")}`);
  const base = id.replace(/[A-Z]$/, "");
  if (base !== id && known(base)) parts.push(`base ${base} exists`);
  return parts.join("; ");
}

const byProgram: { name: string; missing: string[] }[] = [];
const allProgramIds = new Set<string>();
const unknownIds = new Set<string>();
for (const entry of PROGRAMS) {
  const ids = programCourseIds(await entry.load());
  for (const id of ids) allProgramIds.add(id);
  const missing = ids.filter((id) => !known(id));
  for (const id of missing) unknownIds.add(id);
  if (missing.length) byProgram.push({ name: `${entry.name} (${entry.id})`, missing });
}
const missingFromSnapshots = [...allProgramIds].filter((id) => !snapshot.has(id)).length;

const out: string[] = [];
out.push("# Unknown program courses", "");
out.push(
  `Generated by \`packages/plan/scripts/unknown-courses.ts\`. Course ids used by the parsed program requirements that are in neither the Schedule of Classes snapshots (${snapshot.size} courses, current and history) nor the Academic Catalog cache (${catalog.size} courses).`,
  "",
  `- Distinct course ids across ${PROGRAMS.length} programs: ${allProgramIds.size}`,
  `- Missing from the Advisor catalog without the catalog fallback (not in snapshots): ${missingFromSnapshots}`,
  `- Missing with the fallback (unknown to both): ${unknownIds.size}`,
  "",
);
for (const { name, missing } of byProgram) {
  out.push(`## ${name}`, "");
  for (const id of missing) out.push(`- ${id}${hint(id) ? ` (${hint(id)})` : ""}`);
  out.push("");
}
writeFileSync(join(root, "docs", "project", "unknown-courses.md"), out.join("\n"));
console.log(`programs ${PROGRAMS.length}; ids ${allProgramIds.size}; missing from snapshots ${missingFromSnapshots}; unknown to both ${unknownIds.size}`);
